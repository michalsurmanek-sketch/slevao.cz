-- Price alerts are inserted by database triggers. Publish them so an authenticated
-- client can receive its own rows immediately through Supabase Realtime + RLS.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'notifications'
  ) then
    alter publication supabase_realtime add table public.notifications;
  end if;
end
$$;
